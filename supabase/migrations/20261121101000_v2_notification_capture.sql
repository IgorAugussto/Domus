alter table public.credit_cards
  add column if not exists statement_closing_day smallint,
  add column if not exists due_day smallint;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'credit_cards_statement_closing_day_check'
      and conrelid = 'public.credit_cards'::regclass
  ) then
    alter table public.credit_cards
      add constraint credit_cards_statement_closing_day_check
      check (statement_closing_day between 1 and 31) not valid;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'credit_cards_due_day_check'
      and conrelid = 'public.credit_cards'::regclass
  ) then
    alter table public.credit_cards
      add constraint credit_cards_due_day_check
      check (due_day between 1 and 31) not valid;
  end if;
end;
$$;

alter table public.outgoing
  add column if not exists origin varchar(30) not null default 'manual',
  add column if not exists reviewed boolean not null default true,
  add column if not exists purchase_at timestamptz,
  add column if not exists competence_month date;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'outgoing_origin_check'
      and conrelid = 'public.outgoing'::regclass
  ) then
    alter table public.outgoing
      add constraint outgoing_origin_check
      check (origin in ('manual', 'notification', 'statement_import')) not valid;
  end if;
end;
$$;

create table if not exists public.card_aliases (
  id bigint generated by default as identity primary key,
  credit_card_id bigint not null references public.credit_cards(id) on delete cascade,
  alias varchar(100) not null,
  alias_kind varchar(30) not null default 'token',
  created_at timestamptz not null default timezone('utc', now()),
  constraint card_aliases_alias_kind_check check (alias_kind in ('physical', 'virtual', 'token', 'manual')),
  constraint card_aliases_credit_card_alias_unique unique (credit_card_id, alias)
);

create index if not exists card_aliases_credit_card_id_idx
  on public.card_aliases (credit_card_id);

create table if not exists public.notification_events (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete restrict,
  event_key varchar(255) not null,
  source varchar(30) not null,
  source_package varchar(255),
  amount numeric(38, 2) not null,
  merchant varchar(255) not null,
  merchant_normalized varchar(255) not null,
  credit_card_id bigint references public.credit_cards(id) on delete set null,
  outgoing_id bigint references public.outgoing(id) on delete set null,
  occurred_at timestamptz not null,
  received_at timestamptz not null default timezone('utc', now()),
  processed_at timestamptz,
  state varchar(30) not null default 'received',
  simulated boolean not null default false,
  constraint notification_events_event_key_unique unique (user_id, event_key),
  constraint notification_events_amount_check check (amount > 0),
  constraint notification_events_source_check check (source in ('google_wallet', 'nubank', 'whatsapp', 'manual_test', 'other')),
  constraint notification_events_state_check check (state in ('received', 'review', 'processed', 'duplicate', 'ignored'))
);

create index if not exists notification_events_user_occurred_at_idx
  on public.notification_events (user_id, occurred_at desc);
create index if not exists notification_events_candidate_dedup_idx
  on public.notification_events (user_id, amount, merchant_normalized, credit_card_id, occurred_at desc);

create table if not exists public.credit_card_statements (
  id bigint generated by default as identity primary key,
  credit_card_id bigint not null references public.credit_cards(id) on delete restrict,
  statement_month date not null,
  bank_total numeric(38, 2),
  calculated_total numeric(38, 2) not null default 0,
  difference numeric(38, 2) generated always as (coalesce(bank_total, 0) - calculated_total) stored,
  reconciliation_status varchar(30) not null default 'open',
  payment_status varchar(30) not null default 'pending',
  reconciled_at timestamptz,
  notes text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint credit_card_statements_cycle_unique unique (credit_card_id, statement_month),
  constraint credit_card_statements_month_check check (extract(day from statement_month) = 1),
  constraint credit_card_statements_reconciliation_check check (reconciliation_status in ('open', 'reconciled', 'needs_review')),
  constraint credit_card_statements_payment_check check (payment_status in ('pending', 'paid'))
);

create index if not exists credit_card_statements_card_month_idx
  on public.credit_card_statements (credit_card_id, statement_month desc);

